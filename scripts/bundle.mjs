import {readFile,writeFile} from 'node:fs/promises';

// Classic scripts work on file:// as well as static hosts. Keep the renderer
// as an ES module for tests, and generate the browser copy from the same source.
export async function bundle() {
  const strip=source=>source.replace(/^import .*?;\r?\n/gm,'').replace(/^export /gm,'');
  const sources=await Promise.all(['src/svg.js','src/links.js','src/app.js'].map(async path=>strip(await readFile(path,'utf8'))));
  await writeFile('src/browser.js',`// Generated by scripts/bundle.mjs. Edit the source modules.\n(()=>{\n'use strict';\n${sources.join('\n')}\n})();\n`);
}
