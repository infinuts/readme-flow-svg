import {readFile,writeFile} from 'node:fs/promises';

// Classic scripts work on file:// as well as static hosts. Keep the renderer
// as an ES module for tests, and generate the browser copy from the same source.
export async function bundle() {
  const svg=(await readFile('src/svg.js','utf8')).replace(/^export /gm,'');
  const app=(await readFile('src/app.js','utf8')).replace(/^import .*?;\r?\n/,'');
  await writeFile('src/browser.js',`// Generated by scripts/bundle.mjs. Edit src/app.js and src/svg.js.\n(()=>{\n'use strict';\n${svg}\n${app}\n})();\n`);
}
